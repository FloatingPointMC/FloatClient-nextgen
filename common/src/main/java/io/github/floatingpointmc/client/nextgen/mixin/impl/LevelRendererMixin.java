package io.github.floatingpointmc.client.nextgen.mixin.impl;

import io.github.floatingpointmc.client.nextgen.util.render.RenderUtil;
import net.minecraft.client.renderer.LevelRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(LevelRenderer.class)
public class LevelRendererMixin {
    @Inject(method = "finalizeGizmoCollection", at = @At("HEAD"))
    private void floatclient$flushWorldOperations(CallbackInfo ci) {
        RenderUtil.flushWorldOperations((LevelRenderer) (Object) this);
    }
}
