package io.github.floatingpointmc.client.nextgen.ui.shader.state;

import com.mojang.blaze3d.vertex.VertexConsumer;
import com.mojang.renderpearl.api.pipeline.RenderPipeline;
import net.minecraft.client.gui.navigation.ScreenRectangle;
import net.minecraft.client.gui.render.TextureSetup;
import net.minecraft.client.renderer.RenderPipelines;
import net.minecraft.client.renderer.state.gui.GuiElementRenderState;
import org.jetbrains.annotations.Nullable;

/** A zero-vertex GUI batch delimiting a range. A null operation ends the range. */
public record OperationBoundary(ScreenRectangle bounds, @Nullable OperationRenderState.Operation operation)
        implements GuiElementRenderState {
    @Override public void buildVertices(VertexConsumer out) {}
    @Override public RenderPipeline pipeline() { return RenderPipelines.GUI; }
    @Override public TextureSetup textureSetup() { return TextureSetup.noTexture(); }
    @Override public ScreenRectangle scissorArea() { return null; }
}
