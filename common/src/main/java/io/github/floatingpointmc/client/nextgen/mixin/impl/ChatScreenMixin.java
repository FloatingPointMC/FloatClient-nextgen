package io.github.floatingpointmc.client.nextgen.mixin.impl;

import io.github.floatingpointmc.client.nextgen.event.impl.player.ChatEvent;
import io.github.vlouboos.standaloneevent.api.StandaloneEventAPI;
import net.minecraft.client.gui.screens.ChatScreen;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(ChatScreen.class)
public class ChatScreenMixin {
    @Inject(method = "handleChatInput", at = @At(value = "INVOKE", target = "Ljava/lang/String;startsWith(Ljava/lang/String;)Z"), cancellable = true)
    private void onChat(String msg, boolean addToRecent, CallbackInfo ci) {
        ChatEvent event = new ChatEvent(msg);
        StandaloneEventAPI.getApi().call(event);
        if (event.canceled) ci.cancel();
    }
}
